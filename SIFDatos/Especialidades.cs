        public static List<SIFModelo.Especialidad> Busca(string propiedad, string parametro)
        {
            List<SIFModelo.Especialidad> rows = new List<SIFModelo.Especialidad>();

            string sentencia = "SELECT * FROM cat_especialidad";

            using (OracleConnection cnx = new OracleConnection(Helpers.ConnectionString.Connection()))
            {

                using (OracleCommand cmd = new OracleCommand(sentencia, cnx))
                {
                    //
                    cmd.Connection.Open();
                    cmd.ExecuteNonQuery();
                    OracleDataReader oreader = cmd.ExecuteReader(CommandBehavior.SequentialAccess);

                    if (oreader.HasRows)
                    {
                        while (oreader.Read())
                        {
                            SIFModelo.Especialidad registro = new SIFModelo.Especialidad();
                            registro.ID = int.Parse(oreader["ESPECIALIDAD_ID"].ToString());
                            registro.Nombre = oreader["NOMBRE"].ToString();
                            registro.Activo = (SIFModelo.Tipos.SiNo)(oreader["ACTIVO"].ToString()[0]);

                            rows.Add(registro);
                        }
                    }
                    cmd.Connection.Close();
                    cmd.Connection.Dispose();
                   //OracleConnection.ClearPool(cnx);

                }

            }
            return rows;
        }

