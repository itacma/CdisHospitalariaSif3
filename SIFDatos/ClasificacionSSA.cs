        public static List<SIFModelo.ClasificacionSSA> Busca(string propiedad, string parametro)
        {
            List<SIFModelo.ClasificacionSSA> rows = new List<SIFModelo.ClasificacionSSA>();

            string sentencia = "SELECT * FROM ";

            using (OracleConnection cnx = new OracleConnection(Helpers.ConnectionString.Connection()))
            {

                using (OracleCommand cmd = new OracleCommand(sentencia, cnx))
                {
                    //
                    cmd.Connection.Open();
                    cmd.ExecuteNonQuery();
                    OracleDataReader oreader = cmd.ExecuteReader(CommandBehavior.SequentialAccess);

                    if (oreader.HasRows)
                    {
                        while (oreader.Read())
                        {
                            SIFModelo.ClasificacionSSA registro = new SIFModelo.ClasificacionSSA()
                            {
                                ID = int.Parse(oreader["ID"].ToString()),
                                Nombre = oreader["NOMBRE"].ToString(),
                                Receta = (System.Convert.ToChar(oreader["RECETA"]) == 'S' ? SIFModelo.Tipos.SiNo.SI : SIFModelo.Tipos.SiNo.NO),
                            };
                            rows.Add(registro);
                        }
                    }
                    cmd.Connection.Close();
                    cmd.Connection.Dispose();
                   //OracleConnection.ClearPool(cnx);

                }

            }
            return rows;
        }

